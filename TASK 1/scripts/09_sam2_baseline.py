from pathlib import Path
import cv2
import numpy as np
from ultralytics import SAM


# ============================================================
# CONFIG
# ============================================================

DEVELOPMENT_DIR = Path(
    "split_dataset/development"
)

OUTPUT_DIR = Path(
    "task1_segmentation/baseline"
)

OUTPUT_DIR.mkdir(
    parents=True,
    exist_ok=True
)


# ============================================================
# SELECT REPRESENTATIVE IMAGES
# ============================================================

# We deliberately start small.
#
# These are image indices from the development set.
# We will inspect the generated results before processing
# the complete development set.

image_paths = sorted(
    DEVELOPMENT_DIR.glob("*")
)

image_paths = [
    p for p in image_paths
    if p.suffix.lower()
    in {".jpg", ".jpeg", ".png"}
]


# Select approximately 12 images distributed
# throughout the development set.

if len(image_paths) > 12:

    selected = np.linspace(
        0,
        len(image_paths) - 1,
        12,
        dtype=int
    )

    image_paths = [
        image_paths[i]
        for i in selected
    ]


print("=" * 70)
print("Task 1 - SAM 2.1 Baseline")
print("=" * 70)

print(
    f"\nDevelopment images available: "
    f"{len(list(DEVELOPMENT_DIR.glob('*')))}"
)

print(
    f"Images selected for baseline: "
    f"{len(image_paths)}"
)


# ============================================================
# LOAD MODEL
# ============================================================

print("\nLoading SAM 2.1 Base...")

model = SAM("sam2.1_b.pt")

print("Model loaded.")


# ============================================================
# RUN SEGMENT EVERYTHING
# ============================================================

for i, image_path in enumerate(
    image_paths,
    start=1
):

    print(
        f"\n[{i}/{len(image_paths)}] "
        f"{image_path.name}"
    )

    try:

        results = model(
            str(image_path),
            verbose=False
        )

        result = results[0]

        # ----------------------------------------------------
        # Save visualization generated by Ultralytics
        # ----------------------------------------------------

        result.save(
            filename=str(
                OUTPUT_DIR
                /
                f"{image_path.stem}_result.jpg"
            )
        )

        # ----------------------------------------------------
        # Save raw masks
        # ----------------------------------------------------

        if result.masks is not None:

            masks = result.masks.data.cpu().numpy()

            mask_dir = (
                OUTPUT_DIR
                /
                f"{image_path.stem}_masks"
            )

            mask_dir.mkdir(
                parents=True,
                exist_ok=True
            )

            for mask_index, mask in enumerate(
                masks
            ):

                mask_uint8 = (
                    mask.astype(np.uint8)
                    * 255
                )

                cv2.imwrite(
                    str(
                        mask_dir
                        /
                        f"mask_{mask_index:03d}.png"
                    ),
                    mask_uint8
                )

            print(
                f"  Masks generated: "
                f"{len(masks)}"
            )

        else:

            print(
                "  No masks generated."
            )

    except Exception as e:

        print(
            f"  ERROR: {e}"
        )


# ============================================================
# COMPLETE
# ============================================================

print("\n" + "=" * 70)
print("BASELINE COMPLETE")
print("=" * 70)

print(
    f"\nResults saved to:"
)

print(
    OUTPUT_DIR
)